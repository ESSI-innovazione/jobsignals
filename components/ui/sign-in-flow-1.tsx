export const SignInPage = ({ className }: SignInPageProps) => {
  const [step, setStep] = useState<"signin" | "success">("signin");
  const [signingIn, setSigningIn] = useState(false);
  const [initialCanvasVisible, setInitialCanvasVisible] = useState(true);
  const [reverseCanvasVisible, setReverseCanvasVisible] = useState(false);

  // Demo flow: plays the reveal animation and lands on the success screen.
  // The auth milestone replaces this with Supabase Google OAuth:
  //   supabase.auth.signInWithOAuth({ provider: "google", options: { redirectTo: ... } })
  const handleGoogleSignIn = () => {
    if (signingIn) return;
    setSigningIn(true);
    setReverseCanvasVisible(true);
    setTimeout(() => {
      setInitialCanvasVisible(false);
    }, 50);
    setTimeout(() => {
      setStep("success");
    }, 2000);
  };

  return (
    <div
      className={cn(
        "flex w-[100%] flex-col min-h-screen bg-black relative",
        className
      )}
    >
      <div className="absolute inset-0 z-0">
        {/* Initial canvas (forward animation) */}
        {initialCanvasVisible && (
          <div className="absolute inset-0">
            <CanvasRevealEffect
              animationSpeed={3}
              containerClassName="bg-black"
              colors={[
                [255, 255, 255],
                [255, 255, 255],
              ]}
              dotSize={6}
              reverse={false}
            />
          </div>
        )}

        {/* Reverse canvas (plays after the Google sign-in) */}
        {reverseCanvasVisible && (
          <div className="absolute inset-0">
            <CanvasRevealEffect
              animationSpeed={4}
              containerClassName="bg-black"
              colors={[
                [255, 255, 255],
                [255, 255, 255],
              ]}
              dotSize={6}
              reverse={true}
            />
          </div>
        )}

        <div className="absolute inset-0 bg-[radial-gradient(circle_at_center,_rgba(0,0,0,1)_0%,_transparent_100%)]" />
        <div className="absolute top-0 left-0 right-0 h-1/3 bg-gradient-to-b from-black to-transparent" />
      </div>

      {/* Content Layer */}
      <div className="relative z-10 flex flex-col flex-1">
        <MiniNavbar />

        <div className="flex flex-1 flex-col lg:flex-row ">
          <div className="flex-1 flex flex-col justify-center items-center">
            <div className="w-full mt-[150px] max-w-sm">
              <AnimatePresence mode="wait">
                {step === "signin" ? (
                  <motion.div
                    key="signin-step"
                    initial={{ opacity: 0, x: -100 }}
                    animate={{ opacity: 1, x: 0 }}
                    exit={{ opacity: 0, x: -100 }}
                    transition={{ duration: 0.4, ease: "easeOut" }}
                    className="space-y-6 text-center"
                  >
                    <div className="space-y-2">
                      <h1 className="text-6xl sm:text-7xl font-bold leading-[1.05] tracking-tight text-white">
                        Job<span className="text-indigo-400">Signal</span>
                      </h1>
                      <p className="text-[1.4rem] text-white/70 font-light">
                        Il radar delle posizioni aperte
                      </p>
                    </div>

                    <div className="space-y-4">
                      <button
                        onClick={handleGoogleSignIn}
                        disabled={signingIn}
                        className={cn(
                          "backdrop-blur-[2px] w-full flex items-center justify-center gap-3 bg-white/5 hover:bg-white/10 text-white border border-white/10 rounded-full py-3 px-4 transition-colors",
                          signingIn && "opacity-60 cursor-wait"
                        )}
                      >
                        <GoogleIcon className="w-5 h-5" />
                        <span>
                          {signingIn
                            ? "Accesso in corso…"
                            : "Accedi con Google"}
                        </span>
                      </button>
                      <p className="text-sm text-white/40">
                        Usa il tuo account Google{" "}
                        <span className="text-white/60">@timevision.it</span>
                      </p>
                    </div>

                    <p className="text-xs text-white/40 pt-10">
                      Accesso riservato al team TimeVision. Problemi di
                      accesso? Scrivi a{" "}
                      <a
                        href="mailto:innovazione@timevision.it"
                        className="underline text-white/40 hover:text-white/60 transition-colors"
                      >
                        innovazione@timevision.it
                      </a>
                      .
                    </p>
                  </motion.div>
                ) : (
                  <motion.div
                    key="success-step"
                    initial={{ opacity: 0, y: 50 }}
                    animate={{ opacity: 1, y: 0 }}
                    transition={{ duration: 0.4, ease: "easeOut", delay: 0.3 }}
                    className="space-y-6 text-center"
                  >
                    <div className="space-y-1">
                      <h1 className="text-[2.5rem] font-bold leading-[1.1] tracking-tight text-white">
                        Sei dentro!
                      </h1>
                      <p className="text-[1.25rem] text-white/50 font-light">
                        Benvenuto in JobSignal
                      </p>
                    </div>

                    <motion.div
                      initial={{ scale: 0.8, opacity: 0 }}
                      animate={{ scale: 1, opacity: 1 }}
                      transition={{ duration: 0.5, delay: 0.5 }}
                      className="py-10"
                    >
                      <div className="mx-auto w-16 h-16 rounded-full bg-gradient-to-br from-white to-white/70 flex items-center justify-center">
                        <svg
                          xmlns="http://www.w3.org/2000/svg"
                          className="h-8 w-8 text-black"
                          viewBox="0 0 20 20"
                          fill="currentColor"
                        >
                          <path
                            fillRule="evenodd"
                            d="M16.707 5.293a1 1 0 010 1.414l-8 8a1 1 0 01-1.414 0l-4-4a1 1 0 011.414-1.414L8 12.586l7.293-7.293a1 1 0 011.414 0z"
                            clipRule="evenodd"
                          />
                        </svg>
                      </div>
                    </motion.div>

                    <motion.div
                      initial={{ opacity: 0 }}
                      animate={{ opacity: 1 }}
                      transition={{ delay: 1 }}
                    >
                      <Link
                        href="/"
                        className="block w-full rounded-full bg-white text-black font-medium py-3 hover:bg-white/90 transition-colors"
                      >
                        Vai alla dashboard
                      </Link>
                    </motion.div>
                  </motion.div>
                )}
              </AnimatePresence>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
